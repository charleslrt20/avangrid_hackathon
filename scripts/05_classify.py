"""Task 1.3: appliance classification -> appliance inventory + validation report.

Outputs
  outputs/classify.parquet                      per customer (gitignored)
  outputs/summary/appliance_counts.csv          aggregate counts
  outputs/summary/classification_metrics.csv    aggregate metrics
  models/pu_ev.joblib, models/pu_hp.joblib      fitted PU models (gitignored)
  docs/classification.md                        report
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import joblib  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from avangrid import classify as K  # noqa: E402
from avangrid import config as C  # noqa: E402
from avangrid import io  # noqa: E402

lines: list[str] = []


def emit(s: str = "") -> None:
    print(s)
    lines.append(s)


def md(df: pd.DataFrame, index: bool = False) -> None:
    emit(df.to_markdown(index=index, floatfmt=".3g"))
    emit()


def main() -> None:
    t0 = time.time()
    C.ensure_dirs()
    f = pd.read_parquet(C.FEATURES)
    hours = io.load_hours()
    mat = io.load_matrix()
    summer_evening = (hours.month.isin([6, 7, 8]) & hours.hod.between(17, 21)).to_numpy()
    evening_zero = np.nanmean(np.asarray(mat[:, summer_evening]) == 0, axis=1)

    phys = K.physics_flags(f, evening_zero)
    res = pd.concat([f[["customer_id", "in_model", "label_ev", "label_hp", "label_pv"]], phys], axis=1)

    im = f.in_model.to_numpy()
    fm = f[im].reset_index(drop=True)
    X = K.pu_matrix(fm)
    metrics = {}
    for app in ("ev", "hp"):
        y = fm[f"label_{app}"].to_numpy()
        g, model, mt = K.pu_scores(X, y)
        joblib.dump(model, C.MODELS / f"pu_{app}.joblib")
        metrics[app] = mt
        score = np.full(len(f), np.nan)
        score[im] = g
        res[f"{app}_pu_score"] = score
        res[f"{app}_pu_pct"] = pd.Series(score).rank(pct=True).to_numpy()
        metrics[app]["odds"] = K.odds_ratios(model, list(X.columns))

    res["ev_conf"] = K.confidence(res.ev_physics, res.ev_pu_pct)
    hp_phys = res.heat_type.isin(["HP", "HP+backup"])
    res["hp_conf"] = K.confidence(hp_phys, res.hp_pu_pct)
    res.loc[~res.in_model, ["ev_conf", "hp_conf"]] = ""
    res.to_parquet(C.OUTPUTS / "classify.parquet", index=False)

    r = res[res.in_model]
    n = len(r)
    emit("# Appliance classification (task 1.3)")
    emit()
    emit(f"Generated by `scripts/05_classify.py`. Modeling population: {n:,} customers "
         f"({int(r.label_ev.sum())} labeled EV, {int(r.label_hp.sum())} labeled HP, {int(r.label_pv.sum())} PV list).")
    emit()
    emit("**Method.** Flags come from *physics gates* (equipment ratings in `src/avangrid/classify.py`). "
         "EV and HP also get a *PU logistic ranking* (labeled vs unlabeled, 5-fold out-of-fold scores) used to "
         "rank customers and grade confidence. Labels are used only as checks, never to set a threshold.")
    emit()
    emit("**SCAR-implied precision.** If the labeled customers are a random c = 25% of true owners (the brief), "
         "then among any flagged group the labeled share should be 25% x precision. So precision ≈ labeled share / 0.25. "
         "This is only valid if SCAR holds, which the checks below question.")
    emit()

    # ------------------------------------------------------------------ EV
    emit("## EV")
    emit()
    m = metrics["ev"]
    emit(f"- PU logistic CV AUC **{m['cv_auc']:.3f}** (fold s.d. {m['cv_auc_sd']:.3f}); "
         f"benchmark to beat {C.BENCHMARK_AUC['ev']}.")
    emit(f"- Elkan-Noto estimate of c from the data: **{m['c_hat_elkan_noto']:.3f}** vs 0.25 in the brief. "
         "With c = 0.25, the Elkan-Noto rule (g/c ≥ 0.5) flags "
         + ", ".join(f"{m[f'en_flags_c{c}']} (c={c})" for c in C.PU_C_SENSITIVITY)
         + f" customers versus ~{C.IMPLIED_COUNTS['ev']:.0f} implied. **The check fails**: labeled EVs are not "
         "separable enough from the rest for SCAR + c = 0.25 to hold, consistent with the 44% of labeled EVs "
         "that show no home-charging signature (docs/data_checks.md). PU output is therefore used as a ranking.")
    emit()
    cls = r.groupby("ev_class").agg(customers=("customer_id", "size"), labeled_ev=("label_ev", "sum"))
    cls["share_of_customers"] = cls.customers / n
    cls["labeled_recall"] = cls.labeled_ev / r.label_ev.sum()
    cls["scar_precision"] = cls.labeled_ev / cls.customers / C.PU_C
    md(cls.reset_index())
    phys_n = int(r.ev_physics.sum())
    emit(f"Physics EV flag (L2 regular at 5.5-12 kW, or L1 plateau): **{phys_n:,}** customers "
         f"({phys_n / n:.1%}) vs ~{C.IMPLIED_COUNTS['ev']:.0f} implied by the labels (check: the flag count is "
         f"{phys_n / C.IMPLIED_COUNTS['ev']:.1f}x the implied total). Labeled recall {r.ev_physics[r.label_ev].mean():.1%}; "
         f"SCAR-implied precision {K.scar_precision(r.ev_physics, r.label_ev):.0%}.")
    emit()
    emit("PU ranking: labeled share in the top of the ranking (the ranking is out-of-fold, so this is a fair check):")
    emit()
    rows = []
    order = r.sort_values("ev_pu_score", ascending=False)
    for k in (100, 250, 500, 744, 1000, 2000):
        top = order.head(k)
        rows.append({"top_k": k, "labeled_ev": int(top.label_ev.sum()), "labeled_share": top.label_ev.mean(),
                     "scar_precision": top.label_ev.mean() / C.PU_C,
                     "with_physics_signature": top.ev_physics.mean()})
    md(pd.DataFrame(rows))
    conf = r.ev_conf.replace("", "none").value_counts().rename_axis("ev_conf").reset_index(name="customers")
    conf["labeled_ev"] = conf.ev_conf.map(r.assign(ev_conf=r.ev_conf.replace("", "none")).groupby("ev_conf").label_ev.sum())
    conf["scar_precision"] = conf.labeled_ev / conf.customers / C.PU_C
    emit("Confidence tiers (high = physics signature and PU top decile; medium = physics only; "
         "low = PU top 2% without a home-charging signature):")
    emit()
    md(conf)
    emit("Selection-bias check: labeled EVs vs physics-flagged customers who are *not* labeled "
         "(standardised mean difference; |SMD| > 0.2 = notable):")
    emit()
    fb = f[im].reset_index(drop=True)
    sb = K.selection_bias(fb.assign(pv=r.pv.to_numpy()), r.label_ev.to_numpy(),
                          (r.ev_physics & ~r.label_ev).to_numpy(),
                          ["annual_kwh", "peak_kw", "ev_l2_per_week", "ev_l2_block_kw", "ev_l2_evening_share",
                           "heat_slope", "cool_slope", "pv"])
    md(sb.reset_index().rename(columns={"index": "feature"}))
    emit("Top PU coefficients (odds ratio per s.d. after a normal-quantile transform):")
    emit()
    md(m["odds"])

    # ------------------------------------------------------------------ HP / heating
    emit("## Heating type and heat pumps")
    emit()
    m = metrics["hp"]
    emit(f"- PU logistic CV AUC **{m['cv_auc']:.3f}** (fold s.d. {m['cv_auc_sd']:.3f}); benchmark {C.BENCHMARK_AUC['hp']}.")
    emit(f"- Elkan-Noto c from the data: **{m['c_hat_elkan_noto']:.3f}** vs 0.25; flags at c = 0.25: "
         f"{m['en_flags_c0.25']} vs ~{C.IMPLIED_COUNTS['hp']:.0f} implied. Same conclusion as EV: ranking only.")
    emit()
    emit(f"Heat type from the *shape* of the temperature response: electric if heat slope ≥ {K.HEAT_ELECTRIC_SLOPE} "
         f"kWh/day/°F; HP if the slope steepens ≥{K.HP_STEEPEN_RATIO}x below 20 °F, HP+backup if it at least doubles; "
         f"resistive if linear and ≥ {K.HEAT_RESISTIVE_SLOPE}; otherwise electric (type unclear).")
    emit()
    ht = r.groupby("heat_type").agg(customers=("customer_id", "size"), labeled_hp=("label_hp", "sum"),
                                    median_heat_kw_0f=("heat_kw_design_0f", "median"))
    ht["share_of_customers"] = ht.customers / n
    ht["labeled_hp_recall"] = ht.labeled_hp / r.label_hp.sum()
    ht["scar_precision"] = ht.labeled_hp / ht.customers / C.PU_C
    md(ht.reset_index())
    lab_hp = r[r.label_hp]
    emit(f"Labeled HP homes: {lab_hp.electric_heat.mean():.0%} show electric heating at all; "
         f"{lab_hp.heat_type.isin(['HP', 'HP+backup']).mean():.0%} show the HP steepening shape. "
         f"{(~lab_hp.electric_heat).mean():.0%} have a heat slope under {K.HEAT_ELECTRIC_SLOPE}: likely a heat pump "
         "used mainly for cooling or as a supplement to fuel heat (the label marks ownership, not the main heat source).")
    emit()
    emit("Top PU coefficients:")
    emit()
    md(m["odds"])

    # ------------------------------------------------------------------ PV
    emit("## Solar PV")
    emit()
    tp = int((r.pv & r.label_pv).sum())
    prec, rec = tp / max(r.pv.sum(), 1), tp / max(r.label_pv.sum(), 1)
    emit(f"Rule: summer-minus-winter midday zero share ≥ {K.PV_SEASON_CONTRAST} (zeros follow the sun) and summer "
         f"night zeros < {K.PV_MAX_NIGHT_ZERO} (not vacant). Against the complete PV list: precision **{prec:.1%}**, "
         f"recall **{rec:.1%}**, F1 **{2 * prec * rec / (prec + rec):.3f}**. "
         f"Flagged but not on the list (unregistered PV candidates): **{int((r.pv & ~r.label_pv).sum())}**. "
         f"Listed but not flagged: {int((~r.pv & r.label_pv).sum())} (small systems that never export, or a "
         "different meter configuration).")
    emit()
    emit(f"PV homes that also read 0 kWh in ≥{K.PV_BATTERY_EVENING_ZERO:.0%} of summer 17-21h hours (a battery "
         f"covering the evening): **{int(r.pv_battery.sum())}**. Metering is delivered-only, so PV generation and "
         "self-consumption are invisible; these counts are lower bounds.")
    emit()

    # ------------------------------------------------------------------ inventory
    emit("## Appliance inventory")
    emit()
    inv = pd.DataFrame([
        ("EV (L2 or L1 home charging)", r.ev_physics.sum(), "medium-high", "L2 high, L1 medium"),
        ("  of which L2", (r.ev_class == "L2 detectable").sum(), "high", f"median charger {r.ev_charger_kw.median():.1f} kW"),
        ("Electric space heat (any)", r.electric_heat.sum(), "high", ""),
        ("  HP / HP+backup", r.heat_type.isin(["HP", "HP+backup"]).sum(), "medium", "shape of temperature response"),
        ("  resistive", (r.heat_type == "resistive").sum(), "medium", ""),
        ("Central AC", (r.ac_type == "central").sum(), "high", f"median {r.cool_kw_design_90f[r.ac_type == 'central'].median():.1f} kW at 90 °F"),
        ("Room / partial AC", (r.ac_type == "room/partial").sum(), "medium", ""),
        ("Solar PV", r.pv.sum(), "high", "zeros that follow the sun"),
        ("PV + battery", r.pv_battery.sum(), "medium", "lower bound"),
        ("Pool pump", r.pool.sum(), "medium", "timer signature"),
        ("Electric water heater", r.water_heater_lowconf.sum(), "low", "hourly data blurs bursts"),
        ("Hot tub", r.hot_tub_lowconf.sum(), "low", "hourly data blurs cycling"),
    ], columns=["appliance", "customers", "confidence", "note"])
    inv["share"] = inv.customers / n
    md(inv)
    emit("Independent plausibility (to do in task 2.1): compare these shares with EIA RECS Northeast saturation; "
         "RECS is a check only and was not used to tune anything.")
    inv.to_csv(C.OUTPUTS_SUMMARY / "appliance_counts.csv", index=False)
    pd.DataFrame({k: {kk: vv for kk, vv in v.items() if kk != "odds"} for k, v in metrics.items()}).to_csv(
        C.OUTPUTS_SUMMARY / "classification_metrics.csv")
    (C.DOCS / "classification.md").write_text("\n".join(lines) + "\n")
    print(f"\ndone in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
