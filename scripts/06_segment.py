"""Task 1.4: business segments + K-Means shape archetypes + anomalies + unexplained-pattern review.

Outputs
  outputs/segments.parquet                       per customer (gitignored)
  outputs/summary/segment_summary.csv            size and key stats per business segment
  outputs/summary/archetype_centroids.csv        72-dim centroid shapes
  outputs/summary/segment_x_archetype.csv        cross-tab
  docs/segmentation.md, docs/figures/archetypes.png, docs/figures/segments.png
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import kruskal  # noqa: E402
from sklearn.metrics import adjusted_rand_score  # noqa: E402

from avangrid import config as C  # noqa: E402
from avangrid import io  # noqa: E402
from avangrid import plots as P  # noqa: E402
from avangrid import segment as S  # noqa: E402
from avangrid.features.shape import seasonal_profiles  # noqa: E402

K_DEFAULT = 6
lines: list[str] = []


def emit(s: str = "") -> None:
    print(s)
    lines.append(s)


def md(df: pd.DataFrame, index: bool = False) -> None:
    emit(df.to_markdown(index=index, floatfmt=".3g"))
    emit()


def main() -> None:
    t0 = time.time()
    P.style()
    f_all = pd.read_parquet(C.FEATURES)
    k_all = pd.read_parquet(C.OUTPUTS / "classify.parquet")
    prof_all = pd.read_parquet(C.DATA_PROC / "shape_profiles.parquet")
    im = f_all.in_model.to_numpy()
    f, k, prof = (d[im].reset_index(drop=True) for d in (f_all, k_all, prof_all))
    n = len(f)

    seg = S.business_segments(f, k)
    X = S.profile_matrix(prof)
    ksel = S.choose_k(X)
    km = S.fit_archetypes(X, K_DEFAULT)
    # Stable ids: order archetypes by size
    order = np.argsort(-np.bincount(km.labels_))
    remap = {old: new for new, old in enumerate(order)}
    arch = np.array([remap[c] for c in km.labels_])
    centroids = km.cluster_centers_[order]
    names = [S.name_archetype(c) for c in centroids]
    ari = S.bootstrap_ari(X, K_DEFAULT, km.labels_)

    # Interleaved odd/even-week stability: profiles from each half, assigned with the same centroids
    mat = io.load_matrix()
    hours = io.load_hours()
    rows = f.customer_id.map(io.customer_position()).to_numpy()
    halves = {}
    for name, mask in (("odd", hours.odd_week.to_numpy()), ("even", ~hours.odd_week.to_numpy())):
        sub = np.array(mat[rows], dtype=np.float32)
        sub[:, ~mask] = np.nan
        ph = seasonal_profiles(sub, hours)
        ph.insert(0, "customer_id", f.customer_id.to_numpy())
        halves[name] = km.predict(S.profile_matrix(ph))
        del sub
    ari_half = adjusted_rand_score(halves["odd"], halves["even"])
    agree_half = float((halves["odd"] == halves["even"]).mean())

    an = S.anomalies(f, ["annual_kwh", "peak_kw", "load_factor", "winter_summer_ratio", "evening_share",
                         "heat_slope", "cool_slope", "weekend_weekday_ratio", "zero_share", "base_kw_p05"])

    out = pd.DataFrame({"customer_id": f.customer_id, "segment": seg.segment, "archetype": arch,
                        "archetype_name": [names[a] for a in arch]})
    out = pd.concat([out, seg.drop(columns="segment"), an.reset_index(drop=True)], axis=1)
    # customers outside the model population keep a segment that says why
    rest = f_all[~im][["customer_id", "exclude_reason"]].rename(columns={"exclude_reason": "segment"})
    rest["segment"] = "Excluded: " + rest.segment
    pd.concat([out, rest], ignore_index=True).to_parquet(C.OUTPUTS / "segments.parquet", index=False)

    # ---------------------------------------------------------------- report
    emit("# Segmentation (task 1.4)")
    emit()
    emit(f"Generated by `scripts/06_segment.py`. Modeling population {n:,}; "
         f"{int((~im).sum())} customers outside it are reported as 'Excluded: <reason>'.")
    emit()
    emit("## Business segments (primary, rule-based)")
    emit()
    emit("Each customer gets the first segment whose rule fires (priority order below). Peak-contributor "
         f"cut-offs = top 15% of coincident-peak kW: summer ≥ {seg.attrs['thresholds']['cp_kw_summer_p85']:.2f} kW, "
         f"winter ≥ {seg.attrs['thresholds']['cp_kw_winter_p85']:.2f} kW in the system's top {C.PEAK_TOP_HOURS} hours. "
         f"Emerging load = weather-normalised growth ≥ {S.EMERGING_TREND} kWh/day per 30 days.")
    emit()
    g = pd.concat([out, f[["annual_kwh", "cp_kw_summer", "cp_kw_winter", "load_factor"]]], axis=1)
    summ = g.groupby("segment").agg(customers=("customer_id", "size"), median_annual_kwh=("annual_kwh", "median"),
                                    mean_cp_kw_summer=("cp_kw_summer", "mean"), mean_cp_kw_winter=("cp_kw_winter", "mean"),
                                    median_load_factor=("load_factor", "median"),
                                    also_summer_peak=("flag_summer_peak", "mean"), also_winter_peak=("flag_winter_peak", "mean"))
    summ["share"] = summ.customers / n
    summ = summ.reindex([s for s in S.SEGMENT_ORDER if s in summ.index])
    md(summ.reset_index())
    summ.to_csv(C.OUTPUTS_SUMMARY / "segment_summary.csv")
    kw = []
    for col in ["annual_kwh", "cp_kw_summer", "cp_kw_winter", "evening_share", "load_factor"]:
        groups = [x.dropna().to_numpy() for _, x in g.join(f[["evening_share"]]).groupby("segment")[col]]
        h, p = kruskal(*groups)
        kw.append({"feature": col, "kruskal_H": h, "p_value": p,
                   "epsilon_sq": (h - len(groups) + 1) / (n - len(groups))})
    emit("Segments differ on key features (Kruskal-Wallis; ε² effect size, >0.14 = large):")
    emit()
    md(pd.DataFrame(kw))

    emit("## Shape archetypes (K-Means on 72-dim seasonal profiles)")
    emit()
    emit("Profiles are season x hour-of-day load divided by the customer's annual mean, so archetypes group "
         "*when* homes use energy, not how much. Choice of k (silhouette on an 8,000-customer sample):")
    emit()
    md(ksel)
    emit(f"k = {K_DEFAULT} chosen for interpretability; silhouette stays ~0.1 at every k, so these are "
         "**archetypes on a continuum**, not separable clusters.")
    emit()
    emit(f"- Bootstrap stability (20 resamples): ARI mean **{ari.mean():.3f}** (min {ari.min():.3f}).")
    emit(f"- Interleaved odd vs even weeks (same centroids, profiles rebuilt from each half): ARI **{ari_half:.3f}**, "
         f"same archetype for **{agree_half:.1%}** of customers.")
    emit()
    # enrichment of known appliances per archetype (the 'not prescriptive' review)
    tags = pd.DataFrame({"archetype": arch, "EV label": f.label_ev, "HP label": f.label_hp, "PV list": f.label_pv,
                         "EV signature": k.ev_physics, "electric heat": k.electric_heat, "central AC": k.ac_type == "central",
                         "PV signature": k.pv, "pool": k.pool})
    base = tags.drop(columns="archetype").mean()
    lift = tags.groupby("archetype").mean() / base
    review = pd.DataFrame({"archetype": range(K_DEFAULT), "name": names,
                           "customers": np.bincount(arch, minlength=K_DEFAULT),
                           "strongest_enrichment": lift.idxmax(axis=1).to_numpy(),
                           "lift": lift.max(axis=1).round(2).to_numpy()})
    review["explained"] = np.where(review.lift >= 1.5, "yes", "not explained by a detected appliance (lift < 1.5)")
    emit("Archetypes were reviewed *before* mapping them to appliance names: for each, the appliance or label "
         "most over-represented relative to the population (lift). An archetype with no lift ≥ 1.5 is reported "
         "as an unexplained pattern. Here the two unexplained archetypes are the large, balanced-season groups: "
         "ordinary homes whose heating is not electric and whose shape no detected appliance accounts for.")
    emit()
    md(review)
    emit("Full lift table (archetype rate / population rate):")
    emit()
    md(lift.round(2).reset_index())
    pd.DataFrame(centroids, columns=prof.columns[1:]).assign(archetype=range(K_DEFAULT), name=names).to_csv(
        C.OUTPUTS_SUMMARY / "archetype_centroids.csv", index=False)
    ct = pd.crosstab(out.segment, out.archetype)
    ct = ct.reindex([s for s in S.SEGMENT_ORDER if s in ct.index])
    ct.to_csv(C.OUTPUTS_SUMMARY / "segment_x_archetype.csv")
    emit("Business segment x archetype (customers):")
    emit()
    md(ct.reset_index())
    emit("## Anomalies")
    emit()
    a = out[out.anomaly]
    emit(f"IsolationForest on 10 size/shape/weather features flags {len(a)} customers (1%). Their segments:")
    emit()
    md(a.segment.value_counts().rename_axis("segment").reset_index(name="anomalies"))

    # ---------------------------------------------------------------- figures
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.8), sharey=True)
    for j, season in enumerate(["winter", "shoulder", "summer"]):
        for a_ in range(K_DEFAULT):
            axes[j].plot(range(1, 25), centroids[a_, j * 24:(j + 1) * 24], lw=2,
                         label=f"A{a_} ({np.mean(arch == a_):.0%}): {names[a_]}" if j == 0 else None)
        axes[j].set_title(season.title())
        axes[j].set_xlabel("Hour ending")
        axes[j].set_xticks([1, 6, 12, 18, 24])
    axes[0].set_ylabel("Load / customer's annual mean")
    fig.legend(loc="lower center", ncol=2, bbox_to_anchor=(0.5, -0.22), fontsize=8)
    fig.suptitle("Load-shape archetypes (K-Means centroids, k = 6)", fontweight="bold")
    P.save(fig, "archetypes")

    fig, ax = plt.subplots(figsize=(8, 4))
    s2 = summ.iloc[::-1]
    ax.barh(s2.index, s2.customers, color=P.PALETTE[0])
    for y, v in enumerate(s2.customers):
        ax.text(v, y, f" {v:,} ({v / n:.1%})", va="center", fontsize=8)
    ax.set_xlabel("Customers")
    ax.set_title("Business segments (priority rules)")
    ax.grid(axis="y", visible=False)
    P.save(fig, "segments")

    (C.DOCS / "segmentation.md").write_text("\n".join(lines) + "\n")
    print(f"\ndone in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
