"""Task 1.5: what drives load and the summer / winter system peaks.

Outputs
  outputs/summary/peak_contribution_by_segment.csv, ..._by_appliance.csv, ..._by_archetype.csv
  outputs/summary/weather_response_by_segment.csv, temperature_response_by_segment.csv
  docs/drivers.md, docs/figures/{peak_share_by_segment,temperature_response,appliance_peak_kw}.png
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from avangrid import config as C  # noqa: E402
from avangrid import drivers as D  # noqa: E402
from avangrid import io  # noqa: E402
from avangrid import plots as P  # noqa: E402
from avangrid.features import weather as W  # noqa: E402
from avangrid.segment import SEGMENT_ORDER  # noqa: E402

lines: list[str] = []


def emit(s: str = "") -> None:
    print(s)
    lines.append(s)


def md(df: pd.DataFrame, index: bool = False) -> None:
    emit(df.to_markdown(index=index, floatfmt=".3g"))
    emit()


def main() -> None:
    t0 = time.time()
    P.style()
    f_all = pd.read_parquet(C.FEATURES)
    k_all = pd.read_parquet(C.OUTPUTS / "classify.parquet")
    s_all = pd.read_parquet(C.OUTPUTS / "segments.parquet").set_index("customer_id")
    im = f_all.in_model.to_numpy()
    f = f_all[im].reset_index(drop=True)
    k = k_all[im].reset_index(drop=True)
    s = s_all.loc[f.customer_id].reset_index()
    hours = io.load_hours()
    mat = io.load_matrix()
    rows = f.customer_id.map(io.customer_position()).to_numpy()

    # ------------------------------------------------------------- peak contribution
    seg_tab = D.contribution(s.segment, f)
    seg_tab["order"] = seg_tab.group.map({g: i for i, g in enumerate(SEGMENT_ORDER)})
    seg_tab = seg_tab.sort_values("order").drop(columns="order")
    seg_tab.to_csv(C.OUTPUTS_SUMMARY / "peak_contribution_by_segment.csv", index=False)

    app_flags = {
        "EV (home charging)": k.ev_physics, "Electric heat (any)": k.electric_heat,
        "Heat pump (HP / HP+backup)": k.heat_type.isin(["HP", "HP+backup"]),
        "Resistive heat": k.heat_type == "resistive", "Central AC": k.ac_type == "central",
        "Solar PV": k.pv, "Pool pump": k.pool,
    }
    app_rows = []
    for name, flag in app_flags.items():
        t = D.contribution(flag.map({True: name, False: "other"}), f)
        t = t[t.group == name]
        eff_s = D.flag_effect(flag, f.cp_kw_summer)
        eff_w = D.flag_effect(flag, f.cp_kw_winter)
        t["summer_cp_kw_diff"], t["summer_cp_kw_diff_ci"] = eff_s["diff"], f"[{eff_s['lo']:.2f}, {eff_s['hi']:.2f}]"
        t["winter_cp_kw_diff"], t["winter_cp_kw_diff_ci"] = eff_w["diff"], f"[{eff_w['lo']:.2f}, {eff_w['hi']:.2f}]"
        app_rows.append(t)
    app_tab = pd.concat(app_rows, ignore_index=True)
    app_tab.to_csv(C.OUTPUTS_SUMMARY / "peak_contribution_by_appliance.csv", index=False)
    arch_tab = D.contribution(s.archetype_name, f)
    arch_tab.to_csv(C.OUTPUTS_SUMMARY / "peak_contribution_by_archetype.csv", index=False)

    # ------------------------------------------------------------- weather response by segment
    seg_hourly = D.group_hourly_mean(mat, s.segment, rows)
    seg_hourly = seg_hourly.reindex([g for g in SEGMENT_ORDER if g in seg_hourly.index])
    tr = D.temperature_response(seg_hourly, hours.temp.to_numpy())
    tr.to_csv(C.OUTPUTS_SUMMARY / "temperature_response_by_segment.csv")
    wx = W.daily_weather(hours)
    daily = seg_hourly.to_numpy().reshape(len(seg_hourly), 365, 24)
    daily = np.nansum(daily, axis=2) * 24 / np.maximum((~np.isnan(daily)).sum(axis=2), 1)
    wr = D.weather_permutation(daily, wx)
    wr.index = seg_hourly.index
    wr.to_csv(C.OUTPUTS_SUMMARY / "weather_response_by_segment.csv")

    # system-level: total load vs weather
    tot = np.nansum(np.asarray(mat[np.sort(rows)]), axis=0)
    tot_daily = tot.reshape(365, 24).sum(axis=1)[None, :].astype(float)
    sys_coef, _ = W.fit_changepoint(tot_daily, wx)

    # ------------------------------------------------------------- report
    cps, cpw = f.cp_kw_summer.sum(), f.cp_kw_winter.sum()
    emit("# Drivers of load and system peaks (task 1.5)")
    emit()
    emit(f"Generated by `scripts/07_drivers.py`. Modeling population {len(f):,}. Coincident peak (CP) = the system's "
         f"top {C.PEAK_TOP_HOURS} hours in summer (Jun-Sep) and in winter (Dec-Feb). A group's CP share is its share "
         "of total customer load in those hours; 95% CIs from a Poisson bootstrap over customers (500 draws). "
         "Weather → load relationships are causal (weather is exogenous); appliance / segment → peak links are "
         "**associations**.")
    emit()
    emit(f"System: summed CP load {cps / 1000:,.1f} MW summer vs {cpw / 1000:,.1f} MW winter "
         f"(winter = {cpw / cps:.0%} of summer). System daily load rises "
         f"{sys_coef.heat_slope.iat[0] / 1000:,.1f} MWh/day per °F below {sys_coef.heat_bp_f.iat[0]:.1f} °F and "
         f"{sys_coef.cool_slope.iat[0] / 1000:,.1f} MWh/day per °F above {sys_coef.cool_bp_f.iat[0]:.1f} °F, plus "
         f"{sys_coef.cold_slope_extra.iat[0] / 1000:,.1f} MWh/day per °F extra below 20 °F.")
    emit()
    emit("## Share of customers vs share of the system peaks, by business segment")
    emit()
    show = seg_tab[["group", "customers", "share_customers", "share_annual_kwh", "share_cp_kw_summer",
                    "share_cp_kw_summer_lo", "share_cp_kw_summer_hi", "share_cp_kw_winter", "share_cp_kw_winter_lo",
                    "share_cp_kw_winter_hi", "summer_cp_index", "winter_cp_index"]]
    md(show)
    emit("CP index = share of peak / share of customers (1 = average; 2 = each customer contributes twice the average).")
    emit()
    emit("## By appliance (flags overlap; association, not causation)")
    emit()
    md(app_tab[["group", "customers", "share_customers", "share_cp_kw_summer", "share_cp_kw_winter",
                "summer_cp_index", "winter_cp_index", "mean_cp_kw_summer", "mean_cp_kw_winter",
                "summer_cp_kw_diff", "summer_cp_kw_diff_ci", "winter_cp_kw_diff", "winter_cp_kw_diff_ci"]])
    emit("`*_cp_kw_diff` = mean CP kW of customers with the appliance minus those without (bootstrap 95% CI).")
    emit()
    emit("## By shape archetype")
    emit()
    md(arch_tab[["group", "customers", "share_customers", "share_cp_kw_summer", "share_cp_kw_winter",
                 "summer_cp_index", "winter_cp_index"]])
    emit("## Weather response by segment (segment-average home)")
    emit()
    emit("Change-point model on each segment's average daily kWh (balance points held at their fitted values "
         "under the null). Heating / cooling slopes tested against a "
         "day-shuffle null; wind and humidity terms tested by permuting that variable across days within the same "
         "month (200 permutations; p = (exceedances + 1) / 201).")
    emit()
    md(wr.reset_index().rename(columns={"index": "segment"}))
    emit("Wind coefficient = extra heating kWh per heating degree-day per s.d. of wind ('leaky home' effect); "
         "humidity coefficient = extra cooling kWh per cooling degree-day per s.d. of humidity.")
    emit()

    # ------------------------------------------------------------- figures
    fig, ax = plt.subplots(figsize=(9, 5))
    t = seg_tab.iloc[::-1]
    y = np.arange(len(t))
    h = 0.27
    ax.barh(y + h, t.share_customers, h, color=P.NEUTRAL, label="Share of customers")
    ax.barh(y, t.share_cp_kw_summer, h, color=P.SUMMER, label="Share of summer peak",
            xerr=[t.share_cp_kw_summer - t.share_cp_kw_summer_lo, t.share_cp_kw_summer_hi - t.share_cp_kw_summer],
            error_kw={"lw": 0.8})
    ax.barh(y - h, t.share_cp_kw_winter, h, color=P.WINTER, label="Share of winter peak",
            xerr=[t.share_cp_kw_winter - t.share_cp_kw_winter_lo, t.share_cp_kw_winter_hi - t.share_cp_kw_winter],
            error_kw={"lw": 0.8})
    ax.set_yticks(y, t.group)
    ax.xaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
    ax.set_title("Who drives the system peaks: share of customers vs share of peak load")
    ax.legend(loc="center right")
    ax.grid(axis="y", visible=False)
    P.save(fig, "peak_share_by_segment")

    fig, ax = plt.subplots(figsize=(10, 5))
    mids = [iv.mid for iv in tr.columns]
    # Highlight the segments the story is about; the rest stay grey so ten lines stay readable.
    focus = {"Electrified: EV + electric heat": P.PALETTE[2], "Electric-heat home": P.WINTER,
             "Summer peak contributor": P.SUMMER, "EV home": P.PALETTE[1], "Typical": "#000000"}
    other_labeled = False
    for i, g in enumerate(tr.index):
        if g in ("Very high load / non-residential",):
            continue
        hi = g in focus
        ax.plot(mids, tr.loc[g].to_numpy(), lw=2.4 if hi else 1.0, marker="o" if hi else None, ms=3,
                color=focus.get(g, P.NEUTRAL), alpha=1 if hi else 0.6, zorder=3 if hi else 1,
                label=g if hi else (None if other_labeled else "Other segments"))
        other_labeled |= not hi
    ax.set_xlabel("Outdoor temperature (°F)")
    ax.set_ylabel("Average kW per home")
    ax.set_title("Electric heat drives cold-weather load; AC drives hot-weather load")
    ax.legend(fontsize=9, loc="upper left", bbox_to_anchor=(1.01, 1.0))
    P.save(fig, "temperature_response")

    fig, ax = plt.subplots(figsize=(8, 4.5))
    a = app_tab.iloc[::-1]
    y = np.arange(len(a))
    ax.barh(y + 0.2, a.mean_cp_kw_summer, 0.4, color=P.SUMMER, label="Summer peak hours")
    ax.barh(y - 0.2, a.mean_cp_kw_winter, 0.4, color=P.WINTER, label="Winter peak hours")
    ax.axvline(f.cp_kw_summer.mean(), color=P.SUMMER, ls="--", lw=1)
    ax.axvline(f.cp_kw_winter.mean(), color=P.WINTER, ls=":", lw=1)
    ax.set_yticks(y, a.group)
    ax.set_xlabel("Average kW per home during system peak hours (dashed = all homes)")
    ax.set_title("Peak-hour load by appliance")
    ax.legend(loc="lower right")
    ax.grid(axis="y", visible=False)
    P.save(fig, "appliance_peak_kw")

    (C.DOCS / "drivers.md").write_text("\n".join(lines) + "\n")
    print(f"\ndone in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
